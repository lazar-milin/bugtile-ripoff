// Bundles Discord's Embedded App SDK into public/discord-sdk.js. The bundle is committed, so
// playing needs no install; run `npm install && npm run build` only to update the SDK.
import {build} from 'esbuild';
await build({
  stdin:{contents:"export {DiscordSDK} from '@discord/embedded-app-sdk';",resolveDir:process.cwd()},
  bundle:true,format:'esm',minify:true,outfile:'public/discord-sdk.js',
  banner:{js:"// Generated by build.mjs from @discord/embedded-app-sdk. Don't edit by hand; see CLAUDE.md."},
});
console.log('Bundled public/discord-sdk.js');
